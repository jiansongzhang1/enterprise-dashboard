-- 账号启用链接与账号通知邮件
-- 适用于已有数据、需要保留的环境；可重复执行。
-- 新环境使用 ry_20260819_postgresql.sql（已包含本脚本内容）。

-- 1. 账号启用时间：NULL 表示“待启用”（管理员已建号，员工还没通过邮件链接设置密码）
ALTER TABLE IF EXISTS sys_user
    ADD COLUMN IF NOT EXISTS activate_time TIMESTAMP DEFAULT NULL;
COMMENT ON COLUMN sys_user.activate_time IS '账号启用时间；NULL 表示待启用，员工尚未通过邮件链接设置密码';

-- 存量账号都已经能正常登录，视为已启用
UPDATE sys_user
SET activate_time = COALESCE(pwd_update_date, create_time, CURRENT_TIMESTAMP)
WHERE activate_time IS NULL;
