-- Core tables required by login, organization, RBAC, notifications and audit logs.
CREATE TABLE sys_dept (
  dept_id      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 200),
  parent_id    BIGINT DEFAULT 0,
  ancestors    VARCHAR(50) DEFAULT '',
  dept_name    VARCHAR(30) DEFAULT '',
  order_num    INTEGER DEFAULT 0,
  leader       VARCHAR(20) DEFAULT NULL,
  phone        VARCHAR(11) DEFAULT NULL,
  email        VARCHAR(50) DEFAULT NULL,
  status       CHAR(1) DEFAULT '0',
  del_flag     CHAR(1) DEFAULT '0',
  create_by    VARCHAR(64) DEFAULT '',
  create_time  TIMESTAMP,
  update_by    VARCHAR(64) DEFAULT '',
  update_time  TIMESTAMP,
  PRIMARY KEY (dept_id)
);
COMMENT ON TABLE sys_dept IS '部门表';
CREATE TABLE sys_user (
  user_id         BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
  dept_id         BIGINT DEFAULT NULL,
  user_name       VARCHAR(30) NOT NULL,
  nick_name       VARCHAR(30) NOT NULL,
  user_type       VARCHAR(2) DEFAULT '00',
  email           VARCHAR(50) DEFAULT '',
  phonenumber     VARCHAR(11) DEFAULT '',
  sex             CHAR(1) DEFAULT '0',
  avatar          VARCHAR(100) DEFAULT '',
  password        VARCHAR(100) DEFAULT '',
  ga_secret       VARCHAR(64) DEFAULT NULL,
  ga_status       INTEGER DEFAULT 0,
  notification_contacts JSONB NOT NULL DEFAULT '{}'::jsonb,
  status          CHAR(1) DEFAULT '0',
  del_flag        CHAR(1) DEFAULT '0',
  login_ip        VARCHAR(128) DEFAULT '',
  login_date      TIMESTAMP,
  pwd_update_date TIMESTAMP,
  create_by       VARCHAR(64) DEFAULT '',
  create_time     TIMESTAMP,
  update_by       VARCHAR(64) DEFAULT '',
  update_time     TIMESTAMP,
  remark          VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (user_id)
);
COMMENT ON TABLE sys_user IS '用户信息表';

-- Database-level uniqueness is required because service-level
-- check-then-insert validation is not safe under concurrent requests.
CREATE UNIQUE INDEX uk_sys_user_user_name_active
  ON sys_user (user_name) WHERE del_flag = '0';
CREATE UNIQUE INDEX uk_sys_user_email_active
  ON sys_user (email) WHERE del_flag = '0' AND email <> '';
CREATE UNIQUE INDEX uk_sys_user_phone_active
  ON sys_user (phonenumber) WHERE del_flag = '0' AND phonenumber <> '';

CREATE TABLE sys_post (
  post_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
  post_code   VARCHAR(64) NOT NULL,
  post_name   VARCHAR(50) NOT NULL,
  post_sort   INTEGER NOT NULL,
  status      CHAR(1) NOT NULL,
  create_by   VARCHAR(64) DEFAULT '',
  create_time TIMESTAMP,
  update_by   VARCHAR(64) DEFAULT '',
  update_time TIMESTAMP,
  remark      VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (post_id)
);
COMMENT ON TABLE sys_post IS '岗位信息表';
CREATE TABLE sys_role (
  role_id             BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100),
  role_name           VARCHAR(30) NOT NULL,
  role_key            VARCHAR(100) NOT NULL,
  role_sort           INTEGER NOT NULL,
  data_scope          CHAR(1) DEFAULT '1',
  menu_check_strictly  BOOLEAN DEFAULT TRUE,
  dept_check_strictly  BOOLEAN DEFAULT TRUE,
  status              CHAR(1) NOT NULL,
  del_flag            CHAR(1) DEFAULT '0',
  create_by           VARCHAR(64) DEFAULT '',
  create_time         TIMESTAMP,
  update_by           VARCHAR(64) DEFAULT '',
  update_time         TIMESTAMP,
  remark              VARCHAR(500) DEFAULT NULL,
  PRIMARY KEY (role_id)
);
COMMENT ON TABLE sys_role IS '角色信息表';

CREATE UNIQUE INDEX uk_sys_role_name_active
  ON sys_role (role_name) WHERE del_flag = '0';
CREATE UNIQUE INDEX uk_sys_role_key_active
  ON sys_role (role_key) WHERE del_flag = '0';

CREATE TABLE sys_menu (
  menu_id     BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000),
  menu_name   VARCHAR(50) NOT NULL,
  parent_id   BIGINT DEFAULT 0,
  order_num   INTEGER DEFAULT 0,
  path        VARCHAR(200) DEFAULT '',
  component   VARCHAR(255) DEFAULT NULL,
  query       VARCHAR(255) DEFAULT NULL,
  route_name  VARCHAR(50) DEFAULT '',
  is_frame    INTEGER DEFAULT 1,
  is_cache    INTEGER DEFAULT 0,
  menu_type   CHAR(1) DEFAULT '',
  visible     CHAR(1) DEFAULT '0',


  status      CHAR(1) DEFAULT '0',
  perms       VARCHAR(100) DEFAULT NULL,
  icon        VARCHAR(100) DEFAULT '#',
  create_by   VARCHAR(64) DEFAULT '',
  create_time TIMESTAMP,
  update_by   VARCHAR(64) DEFAULT '',
  update_time TIMESTAMP,
  remark      VARCHAR(500) DEFAULT '',
  PRIMARY KEY (menu_id)
);
COMMENT ON TABLE sys_menu IS '菜单权限表';
CREATE TABLE sys_menu_i18n (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
  menu_id     BIGINT NOT NULL,
  locale      VARCHAR(20) NOT NULL,
  menu_name   VARCHAR(100) NOT NULL,
  remark      VARCHAR(500) DEFAULT '',
  created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uk_sys_menu_i18n_menu_locale UNIQUE (menu_id, locale),
  CONSTRAINT fk_sys_menu_i18n_menu FOREIGN KEY (menu_id)
    REFERENCES sys_menu(menu_id) ON DELETE CASCADE
);
COMMENT ON TABLE sys_menu_i18n IS '菜单多语言名称表：支持 zh-CN、zh-TW 和 en-US 菜单展示';

