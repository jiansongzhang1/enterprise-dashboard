-- Foreign keys for relationship integrity.
ALTER TABLE sys_user
  ADD CONSTRAINT fk_sys_user_dept
  FOREIGN KEY (dept_id) REFERENCES sys_dept(dept_id) ON DELETE SET NULL;

ALTER TABLE sys_user_role
  ADD CONSTRAINT fk_sys_user_role_user
  FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE CASCADE,
  ADD CONSTRAINT fk_sys_user_role_role
  FOREIGN KEY (role_id) REFERENCES sys_role(role_id) ON DELETE CASCADE;

ALTER TABLE sys_role_menu
  ADD CONSTRAINT fk_sys_role_menu_role
  FOREIGN KEY (role_id) REFERENCES sys_role(role_id) ON DELETE CASCADE,
  ADD CONSTRAINT fk_sys_role_menu_menu
  FOREIGN KEY (menu_id) REFERENCES sys_menu(menu_id) ON DELETE CASCADE;

ALTER TABLE sys_role_dept
  ADD CONSTRAINT fk_sys_role_dept_role
  FOREIGN KEY (role_id) REFERENCES sys_role(role_id) ON DELETE CASCADE,
  ADD CONSTRAINT fk_sys_role_dept_dept
  FOREIGN KEY (dept_id) REFERENCES sys_dept(dept_id) ON DELETE CASCADE;

ALTER TABLE sys_user_post
  ADD CONSTRAINT fk_sys_user_post_user
  FOREIGN KEY (user_id) REFERENCES sys_user(user_id) ON DELETE CASCADE,
  ADD CONSTRAINT fk_sys_user_post_post
  FOREIGN KEY (post_id) REFERENCES sys_post(post_id) ON DELETE CASCADE;

-- Domain checks for security-sensitive status fields.
ALTER TABLE sys_user
  ADD CONSTRAINT ck_sys_user_type CHECK (user_type IN ('00', '01')),
  ADD CONSTRAINT ck_sys_user_ga_status CHECK (ga_status IN (0, 1, 2));

ALTER TABLE sys_role
  ADD CONSTRAINT ck_sys_role_data_scope CHECK (data_scope IN ('1', '2', '3', '4', '5'));

