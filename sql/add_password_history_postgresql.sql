-- 密码历史：实现「不可與最近 N 次使用的密碼相同」（N 由 user.password.historyCount 配置，默认 3）
-- 适用于已有数据的环境；可重复执行。新环境使用 ry_20260819_postgresql.sql（已包含本脚本内容）。
-- 只存被替换掉的旧密码 BCrypt 值（不存明文）；每个用户只保留最近 N-1 条，「当前密码 + 这 N-1 条」= 最近 N 次
CREATE TABLE IF NOT EXISTS sys_user_pwd_history (
  history_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
  user_id      BIGINT       NOT NULL,
  password     VARCHAR(100) NOT NULL,
  create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (history_id)
);
COMMENT ON TABLE  sys_user_pwd_history IS '用户历史密码：被替换掉的旧密码（BCrypt），用于禁止重复使用最近 N 次密码';
COMMENT ON COLUMN sys_user_pwd_history.password    IS '旧密码 BCrypt 值';
COMMENT ON COLUMN sys_user_pwd_history.create_time IS '该密码被替换的时间';
CREATE INDEX IF NOT EXISTS idx_sys_user_pwd_history_user ON sys_user_pwd_history (user_id, history_id DESC);
